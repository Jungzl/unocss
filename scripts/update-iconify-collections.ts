import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'
import { x } from 'tinyexec'

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)

const COLLECTIONS_FILE = path.resolve(__dirname, '../packages-presets/preset-icons/src/collections.ts')
const COLLECTIONS_API = 'https://api.github.com/repos/iconify/icon-sets/contents/json'
const GENERATED_HEADER = '// Generated by scripts/update-iconify-collections.ts. Do not edit manually.'
// Guard against API glitches silently truncating the generated list.
const MIN_COLLECTIONS = 100

interface GitHubContent {
  name: string
  type: 'file' | 'dir'
}

function isJSONFile(item: unknown): item is GitHubContent {
  if (!item || typeof item !== 'object')
    return false

  const { name, type } = item as Partial<GitHubContent>
  return type === 'file' && typeof name === 'string' && name.endsWith('.json')
}

async function fetchCollections() {
  const headers: Record<string, string> = {
    'Accept': 'application/vnd.github+json',
    'User-Agent': 'unocss-update-iconify-collections',
  }

  if (process.env.GITHUB_TOKEN)
    headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`

  const res = await fetch(COLLECTIONS_API, {
    headers,
    signal: AbortSignal.timeout(30_000),
  })

  if (!res.ok)
    throw new Error(`Failed to fetch iconify collections: ${res.status} ${res.statusText}`)

  const data: unknown = await res.json()
  if (!Array.isArray(data))
    throw new Error(`Unexpected response from ${COLLECTIONS_API}: ${JSON.stringify(data)}`)

  return data
    .filter(isJSONFile)
    .map(item => item.name.slice(0, -'.json'.length))
    .sort()
}

async function update() {
  const collections = await fetchCollections()

  if (collections.length < MIN_COLLECTIONS)
    throw new Error(`Refusing to update with only ${collections.length} iconify collections`)

  const generated = `${GENERATED_HEADER}\nexport default ${JSON.stringify(collections)}\n`
  const previous = await readFile(COLLECTIONS_FILE, 'utf-8').catch(() => '')

  await writeFile(COLLECTIONS_FILE, generated, 'utf-8')
  await x('eslint', ['--fix', '--no-ignore', COLLECTIONS_FILE], { throwOnError: true })

  const updated = await readFile(COLLECTIONS_FILE, 'utf-8')
  if (previous === updated) {
    console.log(`Iconify collections are up to date (${collections.length}).`)
    return
  }

  console.log(`Updated iconify collections (${collections.length}).`)
}

update().catch((error) => {
  console.error(error)
  process.exitCode = 1
})
